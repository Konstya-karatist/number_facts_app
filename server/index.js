function createFallbackFact(number) {
  if (number === 0) {
    return numberFacts[0];
  }

  const parity = number % 2 === 0 ? 'четное' : 'нечетное';
  const sign = number > 0 ? 'положительное' : 'отрицательное';
  const absolute = Math.abs(number);

  return `${number} - ${parity} ${sign} число. Его модуль равен ${absolute}.`;
}

app.get('/', (req, res) => {
  res.json({
    message: 'Number Facts API is running.',
    endpoint: '/api/number/:number',
  });
});

app.get('/api/number/:number', (req, res) => {
  const rawNumber = req.params.number.trim();

  if (!/^-?\d+$/.test(rawNumber)) {
    return res.status(400).json({
      error: 'Number parameter must be an integer.',
      source: 'render-api',
    });
  }

  const number = Number(rawNumber);

  if (!Number.isSafeInteger(number)) {
    return res.status(400).json({
      error: 'Number is outside the safe integer range.',
      source: 'render-api',
    });
  }

  return res.json({
    number,
    fact: numberFacts[number] || createFallbackFact(number),
    source: 'render-api',
  });
});

app.listen(port, () => {
  console.log(`Number Facts API is running on port ${port}`);
});
